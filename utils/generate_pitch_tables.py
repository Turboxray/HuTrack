"""Original HuTrack interpolation tables and exact five-bit volume products."""
from pathlib import Path
import math
ROOT=Path(__file__).resolve().parents[1]
BASE=[3422,3230,3048,2877,2716,2564,2419,2284,2155,2034,1920,1812]
OLD_SINE=[0x00,0x19,0x32,0x4a,0x62,0x78,0x8e,0xa2,0xb4,0xc5,0xd4,0xe1,0xec,0xf4,0xfa,0xfe,
          0xff,0xfe,0xfa,0xf4,0xec,0xe1,0xd4,0xc5,0xb4,0xa2,0x8e,0x78,0x62,0x4a,0x32,0x19]*2

def tables():
    return dict(SquarePos=[((i*i)//4)>>8 for i in range(512)],
                SquareNeg=[(((255-i)**2)//4)>>8 for i in range(512)],
                Volume=[v*env//31 for v in range(32) for env in range(32)],
                BaseLo=[v&255 for v in BASE],BaseHi=[v>>8 for v in BASE],
                Step=[BASE[i]-(BASE[i+1] if i<11 else BASE[0]//2) for i in range(12)],
                OldSine=OLD_SINE,Scale=[i*17 for i in range(16)],
                Sine=[int(127*math.sin(i/64*2*math.pi))&255 for i in range(64)],
                Tremolo=[int(127.5*(1-math.cos(i/128*2*math.pi))) for i in range(128)],
                Semitone=[i%12 for i in range(256)],Octave=[i//12 for i in range(256)])

def render():
    lines=['; Generated by utils/generate_pitch_tables.py. Do not edit by hand.',
           '; Align this block to an 8 KB physical bank, mapped at $8000.',
           'HuTrack.Tables:']
    for name,values in tables().items():
        lines += [f'HuTrack.Pitch.{name}Length = {len(values)}',f'HuTrack.Pitch.{name}:']
        for i in range(0,len(values),16):
            lines.append('    .db '+','.join(f'${v:02x}' for v in values[i:i+16]))
    lines += ['HuTrack.Tables.end:', '    .if ((HuTrack.Tables & $1fff)!=0)',
              '      .fail HuTrack tables must begin at an 8KB bank boundary.', '    .endif',
              '    .if (bank(HuTrack.Tables.end-1)!=bank(HuTrack.Tables))',
              '      .fail HuTrack tables exceed their bank.', '    .endif']
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    (ROOT/'lib/HuTrack/engine/HuTrack_pitch_tables.inc').write_text(render(),newline='\n')
